async def seed():
    async with engine.begin() as conn:
        await conn.run_sync(Base.metadata.create_all)

    async with async_session() as session:
        # Seed songs
        song_count = 0
        for song_data in SONGS:
            existing = await session.execute(
                select(Song).where(Song.title == song_data["title"], Song.composer == song_data["composer"])
            )
            if existing.scalar_one_or_none() is None:
                song = Song(id=str(uuid.uuid4()), **song_data)
                session.add(song)
                song_count += 1

        # Seed skills
        skill_count = 0
        for skill_data in SKILLS:
            existing = await session.execute(
                select(Skill).where(Skill.name == skill_data["name"])
            )
            if existing.scalar_one_or_none() is None:
                skill = Skill(id=str(uuid.uuid4()), **skill_data)
                session.add(skill)
                skill_count += 1

        await session.commit()
        print(f"Seeded {song_count} songs, {skill_count} skills.")


if __name__ == "__main__":
    asyncio.run(seed())
